"""
Prepares Haruka's poses for SibukSeharian from assets/Haruka.

Each pose is upscaled (the phone and laptop crops are only ~300-700 px), given the storyboard's
white sticker outline, and written to public/sibuk/haruka/<key>.png. The script also measures,
in output pixels, the crown of her hair (`top`), her head's centre (`cx`) and the hair's width
(`headW`), and writes them to src/sibuk/poses.ts so <Haruka> can keep her head pinned and the
same size while the pose changes.

Run: python3 scripts/make-sibuk-art.py
"""
import os

import numpy as np
from PIL import Image, ImageFilter
from scipy import ndimage

SRC = "assets/Haruka"
OUT = "public/sibuk/haruka"

# key: (asset file, what she is doing in the video)
POSES = {
    "puzzled": ("haruka-hand-on-chin-puzzled-with-question-mark.png", "S2: 16.47, still one sentence"),
    "startled": ("haruka-holding-phone-surprised-02.png", "S3: the phone buzzes"),
    "reading": ("haruka-holding-phone-tapping-screen-curious-03.png", "S3: reads the group chat"),
    "weighing": ("haruka-holding-phone-hand-on-chin-skeptical.png", "S4: 'Bisa bantu cek sebentar?'"),
    "replying": ("haruka-holding-phone-tapping-screen-curious-02.png", "S4: types 'Oke, bentar ya'"),
    "meeting": ("haruka-at-laptop-hand-on-chin-focused-02.png", "S5a: meeting"),
    "email": ("haruka-at-laptop-hand-on-chin-focused.png", "S5b: email, close-up"),
    "revisi": ("haruka-at-laptop-hands-on-head-frustrated-02.png", "S5c: revisi"),
    "chat": ("haruka-at-laptop-hands-on-head-overwhelmed-with-paperwork.png", "S5d: chat lagi, spiral eyes"),
    "panic": ("haruka-both-palms-forward-panicking.png", "S5e: surrounded by notifications"),
    "tired": ("haruka-holding-phone-facepalming-exasperated.png", "S6: rubs her face"),
    "worried": ("haruka-hands-clasped-worried.png", "S6: 'nggak ada yang buat proposal'"),
    "hand": ("haruka-hand-writing.png", "S7: writes the next task"),
    "asking": ("haruka-index-finger-raised-open-palm-smiling.png", "S8: asks the question"),
    "pointDown": ("haruka-pointing-down-open-palm-smiling.png", "S8: points at the CTA"),
}

MIN_SIDE = 1100  # upscale until the longer side is at least this


def hair_mask(rgba):
    a = rgba[..., 3] > 200
    r, g, b = (rgba[..., i].astype(int) for i in range(3))
    brown = (r > g) & (g >= b - 4) & (r - b > 22) & (r < 205) & (r > 55)
    return a & brown


def measure(img):
    rgba = np.array(img)
    mask = hair_mask(rgba)
    mask = ndimage.binary_opening(mask, iterations=2)
    lab, n = ndimage.label(mask)
    if n == 0:
        return 0, img.width // 2, img.width // 3
    sizes = ndimage.sum(mask, lab, range(1, n + 1))
    hair = lab == (int(np.argmax(sizes)) + 1)
    ys, xs = np.nonzero(hair)
    top = int(ys.min())
    span = int(ys.max() - top)
    band = hair[top + int(span * 0.12) : top + int(span * 0.3)]
    bx = np.nonzero(band.any(axis=0))[0]
    cols = np.nonzero(hair[top : top + int(span * 0.3)].any(axis=0))[0]
    cx = int(round((np.percentile(cols, 3) + np.percentile(cols, 97)) / 2))
    head_w = int(bx.max() - bx.min()) if len(bx) else img.width // 3
    return top, cx, head_w


def sticker(img, radius):
    """White outline under the cut-out, like the storyboard's stickers."""
    pad = radius + 4
    w, h = img.size
    canvas = Image.new("RGBA", (w + 2 * pad, h + 2 * pad), (0, 0, 0, 0))
    canvas.paste(img, (pad, pad), img)
    alpha = np.array(canvas)[..., 3] > 40
    yy, xx = np.mgrid[-radius : radius + 1, -radius : radius + 1]
    disk = xx * xx + yy * yy <= radius * radius
    grown = ndimage.binary_dilation(alpha, structure=disk)
    grown = ndimage.binary_fill_holes(grown)
    edge = Image.fromarray((grown * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(1.2))
    white = Image.new("RGBA", canvas.size, (255, 253, 248, 255))
    white.putalpha(edge)
    white.alpha_composite(canvas)
    return white, pad


os.makedirs(OUT, exist_ok=True)
rows = []
for key, (file, note) in POSES.items():
    img = Image.open(os.path.join(SRC, file)).convert("RGBA")
    k = max(1, int(np.ceil(MIN_SIDE / max(img.size))))
    if k > 1:
        img = img.resize((img.width * k, img.height * k), Image.LANCZOS)
    top, cx, head_w = measure(img)
    radius = max(8, round(head_w * 0.035)) if key != "hand" else 12
    out, pad = sticker(img, radius)
    out.save(os.path.join(OUT, f"{key}.png"), optimize=True)
    rows.append((key, out.width, out.height, top + pad, cx + pad, head_w, file, note))
    print(f"{key:10s} {file:62s} x{k} -> {out.width}x{out.height} top={top + pad} cx={cx + pad} headW={head_w}")

ts = [
    "// Generated by scripts/make-sibuk-art.py from assets/Haruka. Do not edit by hand.",
    "// `top` is the crown of her hair and `cx` her head's centre, in image pixels (public/sibuk/haruka/<key>.png);",
    "// `headW` is the hair's width near the top of her head, used to keep her the same size across poses.",
    "export const POSES = {",
]
for key, w, h, top, cx, head_w, file, note in rows:
    ts.append(f'  {key}: {{ w: {w}, h: {h}, top: {top}, cx: {cx}, headW: {head_w} }}, // {file.removeprefix("haruka-")} · {note}')
ts += ["} as const;", "", "export type Pose = keyof typeof POSES;", ""]
os.makedirs("src/sibuk", exist_ok=True)
with open("src/sibuk/poses.ts", "w") as f:
    f.write("\n".join(ts))
print("wrote src/sibuk/poses.ts")
